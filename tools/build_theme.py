"""Construit le thème distribué (themes/braise_glass.yaml) à partir de la source.

Usage : python tools/build_theme.py

src/braise_glass.yaml contient deux marqueurs, {{BACKDROP_DARK}} et
{{BACKDROP_LIGHT}}, remplacés ici par les décors SVG de assets/ encodés en
data URI. Le thème distribué est ainsi autonome : HACS n'installe que le
dossier themes/, aucun fichier n'est à copier dans /config/www.

Les variantes de couleur (VARIANTS) sont générées à partir de la même source
par rotation de teinte (tools/recolor.py) et ajoutées au même fichier.
"""

from __future__ import annotations

import base64
import re
from pathlib import Path

from recolor import recolor_svg, recolor_yaml

ROOT = Path(__file__).resolve().parent.parent
HEADER = (
    "# ⚠ Fichier généré par tools/build_theme.py — modifier src/braise_glass.yaml\n"
    "# ⚠ Generated by tools/build_theme.py — edit src/braise_glass.yaml instead\n"
)
BASE_NAME = "Braise Glass"
BACKDROPS = (("{{BACKDROP_DARK}}", "braise_glass_dark.svg"), ("{{BACKDROP_LIGHT}}", "braise_glass_light.svg"))

# Variantes : nom affiché dans Home Assistant, préfixe d'ancres YAML,
# rotation de teinte OKLCH (degrés) appliquée aux couleurs de marque.
VARIANTS = [
    {"name": "Braise Glass Amethyst", "anchor": "amethyst", "hue": 260},
]

ANCHOR_RE = re.compile(r"(?<=\s)([&*])([a-z][a-z0-9_]*)")


def data_uri(svg: str) -> str:
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("utf-8")).decode("ascii")


def embed(src: str, hue: float = 0) -> str:
    for marker, name in BACKDROPS:
        if marker not in src:
            raise SystemExit(f"marqueur {marker} absent de src/braise_glass.yaml")
        svg = (ROOT / "assets" / name).read_text(encoding="utf-8")
        src = src.replace(marker, data_uri(recolor_svg(svg, hue) if hue else svg))
    return src


def variant(src: str, v: dict) -> str:
    """Copie recolorée des thèmes (normal + Lite), renommée, aux ancres préfixées."""
    body = src[src.index(f"{BASE_NAME}: &"):]
    body = recolor_yaml(body, v["hue"])
    body = ANCHOR_RE.sub(lambda m: f"{m.group(1)}{v['anchor']}_{m.group(2)}", body)
    for old in (f"{BASE_NAME} Lite", BASE_NAME):  # Lite d'abord : il contient le nom de base
        body = re.sub(rf"^{old}:", f"{v['name']}{old[len(BASE_NAME):]}:", body, flags=re.M)
        body = body.replace(f'card-mod-theme: "{old}"', f'card-mod-theme: "{v["name"]}{old[len(BASE_NAME):]}"')
    banner = (
        "\n# " + "=" * 77 + "\n"
        f"#  {v['name'].upper()} — variante générée (teinte +{v['hue']}° OKLCH)\n"
        "#  Même design que Braise Glass ; ne pas modifier : éditer src/ puis rebuild.\n"
        "# " + "=" * 77 + "\n"
    )
    return banner + embed(body, v["hue"])


def main() -> None:
    src = (ROOT / "src" / "braise_glass.yaml").read_text(encoding="utf-8")
    out_text = HEADER + embed(src) + "".join(variant(src, v) for v in VARIANTS)
    out = ROOT / "themes" / "braise_glass.yaml"
    out.parent.mkdir(exist_ok=True)
    out.write_text(out_text, encoding="utf-8", newline="\n")
    print(f"{out} ({out.stat().st_size // 1024} Ko)")


if __name__ == "__main__":
    main()
